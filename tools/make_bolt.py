#!/usr/bin/env python3
"""Generate src/bolt_data.h: Bolt's remarks, taken from the GBA game's ui.inc (read only): usage make_bolt.py /home/claude/bugstar/ui.inc src/bolt_data.h"""
import re, sys
t = open(sys.argv[1]).read()
def arr(name):
    m = re.search(r'static const char \*const %s\[[^\]]*\](?:\[\d+\])?\s*=\s*\{(.*?)\};' % name, t, re.S)
    body = m.group(1)
    return [s.replace('\\"', '').replace('"', '') if False else s for s in re.findall(r'"((?:[^"\\]|\\.)*)"', body)]
def clean(s): return s.replace('\\"', '').strip()
out = ['/* generated by tools/make_bolt.py from the GBA game\'s ui.inc: Bolt\'s remarks (do not edit by hand) */\n']
def emit(name, items, shape=None):
    items = [clean(s) for s in items]
    out.append('static const char *const %s[%d] = {\n' % (name, len(items)) + ',\n'.join('    "%s"' % s for s in items) + '\n};\n')
for n in ('bolt_idle', 'bolt_zone', 'bolt_cls', 'bolt_trait'): emit(n, arr(n))
mem = arr('bolt_mem'); emit('bolt_mem', mem)   # 8 x 4 lines, row major
open(sys.argv[2], 'w').write(''.join(out))
print({n: len(arr(n)) for n in ('bolt_idle', 'bolt_zone', 'bolt_cls', 'bolt_trait', 'bolt_mem')})
