#!/usr/bin/env python3
"""BUGSTAR GBC hyperspace tunnel (the 3D warp). Writes src/warp_art.c + src/warp_art.h (bank 9) and tools/warp_check.png.

The tunnel is a still picture whose colour index is the depth ring a pixel sees (depth = K / distance from the middle), so cycling
the 4 colours makes the rings stream towards you. Eight thin spokes cut the rings into segments. Only the top-left quarter is stored
(the rest is the same tiles mirrored with the CGB's flip bits). Each tile gets one of 4 fog palettes by its distance from the middle:
far rings are dim, near ones bright. The palettes are stored for all 4 steps of the cycle.

Run:  python3 tools/make_warp.py
"""
import math, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAMP = [(1, 1, 6), (4, 6, 18), (10, 16, 30), (24, 29, 31)]      # dark -> bright, 5-bit
FOG = [0.24, 0.48, 0.74, 1.0]                                  # far -> near


def pix(x, y):
    dx, dy = x + 0.5 - 80, y + 0.5 - 72
    d = math.hypot(dx, dy)
    ring = int(520 / (d + 7))
    a = math.atan2(dy, dx) % (math.pi / 4)
    spoke = min(a, math.pi / 4 - a) * d < 0.9 and d > 10        # 8 thin spokes, on the axes and the diagonals
    return (ring + (2 if spoke else 0)) & 3


def rock(r, seed):                                       # a lumpy rock, lit from the top left, in a 16x16 (or smaller) box
    import random
    R = random.Random(seed); n = 16; g = [[0] * n for _ in range(n)]
    bumps = [R.uniform(-0.18, 0.18) for _ in range(12)]
    for y in range(n):
        for x in range(n):
            dx, dy = x + 0.5 - n / 2, y + 0.5 - n / 2; d = math.hypot(dx, dy); a = math.atan2(dy, dx)
            rr = r * (1 + bumps[int((a + math.pi) / (2 * math.pi) * 12) % 12])
            if d < rr:
                lit = (-dx - dy) / (rr * 1.4)
                g[y][x] = 3 if lit > 0.35 else 2 if lit > -0.35 else 1
                if d > rr - 1: g[y][x] = 1
    for k in range(3):                                   # craters
        cx, cy = R.uniform(-r / 2, r / 2) + n / 2, R.uniform(-r / 2, r / 2) + n / 2
        for y in range(n):
            for x in range(n):
                if g[y][x] and math.hypot(x + 0.5 - cx, y + 0.5 - cy) < r / 4: g[y][x] = 1
    return g


def shard(r):                                            # a hot 4-point star
    n = 16; g = [[0] * n for _ in range(n)]
    for y in range(n):
        for x in range(n):
            dx, dy = abs(x + 0.5 - 8), abs(y + 0.5 - 8)
            v = min(dx, dy) * 3 + max(dx, dy) * 0.6
            if v < r: g[y][x] = 3 if v < r * 0.4 else 2 if v < r * 0.7 else 1
    return g


def small(g16):                                          # an 8x16 sprite: the 16x16 picture halved, in the top 8 rows
    out = [[0] * 8 for _ in range(16)]
    for y in range(8):
        for x in range(8):
            q = [g16[y * 2 + a][x * 2 + b] for a in (0, 1) for b in (0, 1)]
            out[y][x] = max(q) if sum(1 for v in q if v) >= 2 else 0
    return out


def spr16(g):                                            # 16x16 -> two 8x16 sprites (left column, then right)
    col = lambda x0: [[g[y][x0 + x] for x in range(8)] for y in range(16)]
    return tile8x16(col(0)) + tile8x16(col(8))


def tile8x16(g): return tile2bpp(g[:8]) + tile2bpp(g[8:])


def tile2bpp(g):
    out = []
    for row in g:
        lo = hi = 0
        for x, v in enumerate(row): lo |= (v & 1) << (7 - x); hi |= ((v >> 1) & 1) << (7 - x)
        out += [lo, hi]
    return out


def main():
    tiles, index, tmap, attr = [], {}, [], []
    for ty in range(9):                                        # the top-left quarter: 10 x 9 tiles
        for tx in range(10):
            g = [[pix(tx * 8 + x, ty * 8 + y) for x in range(8)] for y in range(8)]
            key = tuple(map(tuple, g))
            if key not in index: index[key] = len(tiles); tiles.append(g)
            tmap.append(index[key])
            d = math.hypot(tx * 8 + 4 - 80, ty * 8 + 4 - 72)
            attr.append(0 if d < 22 else 1 if d < 42 else 2 if d < 70 else 3)
    full_t, full_a = [], []
    for y in range(18):
        for x in range(20):
            qx, fx = (x, 0) if x < 10 else (19 - x, 0x20)
            qy, fy = (y, 0) if y < 9 else (17 - y, 0x40)
            full_t.append(tmap[qy * 10 + qx]); full_a.append(0x08 | (4 + attr[qy * 10 + qx]) | fx | fy)
    pals = []
    for ph in range(4):
        for f in FOG:
            for i in range(4):
                r, g, b = RAMP[(i + ph) & 3]
                pals.append("RGB(%d,%d,%d)" % (max(1, int(r * f)), max(1, int(g * f)), max(3, int(b * f))))
    c = ["#pragma bank 9", "/* generated by tools/make_warp.py: do not edit */", "#include <gb/gb.h>", "#include <gb/cgb.h>", '#include "warp_art.h"']
    c.append("const UINT8 warp_tiles[WARP_NTILES * 16] = {" + ",".join("0x%02X" % b for t in tiles for b in tile2bpp(t)) + "};")
    c.append("const UINT8 warp_map[360] = {" + ",".join(map(str, full_t)) + "};")
    c.append("const UINT8 warp_attr[360] = {" + ",".join("0x%02X" % a for a in full_a) + "};")
    c.append("const palette_color_t warp_pals[4 * 16] = {" + ",".join(pals) + "};")
    rk1, rk2, sh = rock(7.2, 3), rock(7.2, 9), shard(9)
    spr = spr16(rk1) + spr16(rk2) + tile8x16(small(rk1)) + spr16(sh) + tile8x16(small(sh))
    c.append("const UINT8 warp_spr[WARP_NSPR * 16] = {" + ",".join("0x%02X" % b for b in spr) + "};")
    c.append("const UINT16 warp_rz[256] = {" + ",".join(str(min(65535, 4096 // max(z, 1))) for z in range(256)) + "};")
    open(os.path.join(ROOT, "src", "warp_art.c"), "w").write("\n".join(c) + "\n")
    h = ["#ifndef WARP_ART_H", "#define WARP_ART_H", "#include <gb/gb.h>", "#include <gb/cgb.h>",
         "/* generated by tools/make_warp.py: the hyperspace tunnel (bank 9) */",
         "#define WARP_NTILES %d                 /* VRAM bank 1 from tile 0 */" % len(tiles),
         "extern const UINT8 warp_tiles[WARP_NTILES * 16];",
         "extern const UINT8 warp_map[360];               /* 20 x 18 tile numbers */",
         "extern const UINT8 warp_attr[360];              /* fog palette 4..7, bank 1, flips */",
         "extern const palette_color_t warp_pals[4 * 16]; /* BG palettes 4..7 for each of the 4 steps of the cycle */",
         "#define WARP_T_ROCK(f)  ((f) * 4)       /* sprite tiles (8x16 mode), from wherever they are loaded: a 16x16 meteor, 2 looks */",
         "#define WARP_T_ROCK_S   8               /* a far meteor, 8x8 in the top of an 8x16 */",
         "#define WARP_T_SHARD    10              /* a hot star shard, 16x16 */",
         "#define WARP_T_SHARD_S  14",
         "#define WARP_NSPR       16",
         "extern const UINT8 warp_spr[WARP_NSPR * 16];",
         "extern const UINT16 warp_rz[256];               /* 4096 / z: the perspective divide, as a multiply */",
         "#endif"]
    open(os.path.join(ROOT, "src", "warp_art.h"), "w").write("\n".join(h) + "\n")
    try:
        from PIL import Image
        im = Image.new("RGB", (160, 144))
        for y in range(144):
            for x in range(160):
                tx, ty = x // 8, y // 8
                a = full_a[ty * 20 + tx]; f = FOG[(a & 7) - 4]
                r, g, b = RAMP[pix(x, y)]
                im.putpixel((x, y), (int(r * f * 8), int(g * f * 8), int(b * f * 8)))
        im.resize((480, 432), 0).save(os.path.join(ROOT, "tools", "warp_check.png"))
    except ImportError:
        pass
    print("warp: %d tiles" % len(tiles))


if __name__ == "__main__":
    main()
