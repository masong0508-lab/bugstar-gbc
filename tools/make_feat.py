#!/usr/bin/env python3
"""BUGSTAR GBC small art for the extras (pets): writes src/feat_art.c (bank 20).
A pet is a little copy of your bug seen from the side: one 8x16 sprite (art in the bottom 8 rows), two frames (legs). Palette 4 (the bug's own)."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
F0 = ["........"] * 8 + [
    "..1..1..", "..1111..", ".122221.", "12233221", "12222221", ".111111.", "1.1..1.1", "........"]
F1 = ["........"] * 8 + [
    "..1..1..", "..1111..", ".122221.", "12233221", "12222221", ".111111.", ".1.11.1.", "........"]
def tile(rows, y0):
    out = []
    for y in range(8):
        lo = hi = 0
        r = rows[y0 + y]
        for x in range(8):
            v = ".123".index(r[x]); lo |= (v & 1) << (7 - x); hi |= ((v >> 1) & 1) << (7 - x)
        out += [lo, hi]
    return out
t = tile(F0, 0) + tile(F0, 8) + tile(F1, 0) + tile(F1, 8)
open(os.path.join(ROOT, "src", "feat_art.c"), "w").write(
    "#pragma bank 20\n/* generated by tools/make_feat.py: do not edit */\n#include <gb/gb.h>\n#include \"feat.h\"\nconst UINT8 pet_tiles[64] = {" + ",".join("0x%02X" % b for b in t) + "};\n")
print("feat art: pet 2 frames")
