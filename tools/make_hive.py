def enc(rows):
    out = []
    for r in rows:
        lo = hi = 0
        for i, c in enumerate(r):
            v = int(c); lo |= (v & 1) << (7 - i); hi |= (v >> 1) << (7 - i)
        out += [lo, hi]
    return out
def arr(names):
    b = []
    for n in names: b += enc(T[n])
    return ','.join('0x%02X' % x for x in b)
